"""Builds the browser engine's assets from a domOXML checkout.

- public/engine/: the domOXML wheel plus the one pure-Python dependency Pyodide doesn't ship.
- src/engine/ir.gen.ts: TypeScript types for domOXML's IR, generated from its JSON schema.
- src/engine/capture.gen.ts: domOXML's own in-page capture scripts (canvas recorder + layout
  snapshot), exported verbatim so the web backend can never drift from the Chromium one.

usage: <domOXML venv>/bin/python scripts/build-engine.py [path/to/domOXML]
"""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
import urllib.request
from pathlib import Path

APP = Path(__file__).resolve().parents[1]
SRC = Path(sys.argv[1] if len(sys.argv) > 1 else Path.home() / "domOXML").resolve()
OUT = APP / "public/engine"
DEFUSEDXML = "https://files.pythonhosted.org/packages/07/6c/aa3f2f849e01cb6a001cd8554a88d4c77c5c1a31c95bdf1cf9301e6d9ef4/defusedxml-0.7.1-py2.py3-none-any.whl"


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.whl"):
        old.unlink()
    dist = APP / "node_modules/.cache/domoxml-dist"
    shutil.rmtree(dist, ignore_errors=True)
    subprocess.run(["uv", "build", "--wheel", "--out-dir", str(dist)], cwd=SRC, check=True)
    wheel = next(dist.glob("domoxml-*.whl"))
    shutil.copy(wheel, OUT / wheel.name)
    defused = OUT / DEFUSEDXML.rsplit("/", 1)[1]
    urllib.request.urlretrieve(DEFUSEDXML, defused)
    rev = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=SRC, capture_output=True, text=True, check=True).stdout.strip()
    (OUT / "manifest.json").write_text(json.dumps({"domoxml": wheel.name, "deps": [defused.name], "rev": rev}, indent=2))

    sys.path.insert(0, str(SRC))
    from domoxml.core.render import browser
    from domoxml.core.render.canvas_recorder import RECORDER_JS

    gen = APP / "src/engine/capture.gen.ts"
    gen.write_text(
        f"// Generated by scripts/build-engine.py from domOXML {rev}. Do not edit.\n"
        f"export const RECORDER_JS = {json.dumps(RECORDER_JS)}\n"
        f"export const SNAPSHOT_JS = {json.dumps(browser._SNAPSHOT_JS)}\n"
    )
    # The IR's JSON shape (as serialized), for generated TypeScript types: the editor reads and
    # writes IR (text payloads, per-node splices) without a hand-written mirror.
    from domoxml.core.ir import SlideIR

    schema = SlideIR.model_json_schema(mode="serialization")
    schema_path = APP / "node_modules/.cache/domoxml-ir.schema.json"
    schema_path.write_text(json.dumps(schema))
    subprocess.run(
        ["npx", "json2ts", "--input", str(schema_path), "--output", str(APP / "src/engine/ir.gen.ts"),
         "--bannerComment", f"// Generated by scripts/build-engine.py from domOXML {rev}'s IR schema. Do not edit.",
         "--additionalProperties", "false", "--unreachableDefinitions"],
        cwd=APP, check=True,
    )
    print(f"engine: {wheel.name} + {defused.name} (domOXML {rev})")


main()
